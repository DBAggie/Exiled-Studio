//! `pob-skills`: generates `crates/loom-calc/src/poe1/pob_skills.rs`, PoB
//! v2.67.2's hand-written skill data (Phase 6 plan, decision 5;
//! `loom_calc::poe1::pob_skill`), from the PoB data export
//! (`tools/oracle/data/pob_data.lua`, format 10 or later): each skill's
//! `base_flags`, `parts`, base mods (the `mods` entry with stat `""`), and
//! `functions`, and (format 13, P6-7b1) its `minions` and `add_minions`
//! lists in PoB's order. A skill with none of them is left out. Two runs on
//! the same export give the same bytes.
//!
//! `pob-minions` ([`generate_minions`]) generates
//! `crates/loom-calc/src/poe1/pob_minions.rs` from the export's
//! `minion_templates` (format 13): each minion PoB's templates emit, by
//! PoB's name, with the directives that add to the game's variety.

use std::fmt::Write as _;
use std::path::Path;

use serde_json::Value;

/// The export's first format with the skill data.
const MIN_FORMAT: u64 = 10;

/// The export's first format with the minion templates (P6-7b1).
const MINION_FORMAT: u64 = 13;

fn lit_str(s: &str) -> String {
    format!("{s:?}")
}

fn lit_num(n: f64) -> String {
    let s = format!("{n:?}");
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}

/// A plain JSON value as a `Value` literal; `None` for anything else.
fn lit_value(v: &Value) -> Option<String> {
    match v {
        Value::Bool(b) => Some(format!("V::Bool({b})")),
        Value::Number(n) => n.as_f64().map(|n| format!("V::Num({})", lit_num(n))),
        Value::String(s) => Some(format!("V::Str({})", lit_str(s))),
        _ => None,
    }
}

fn bits(v: Option<&Value>) -> u64 {
    v.and_then(Value::as_u64).unwrap_or(0)
}

/// The Rust source of the table.
///
/// # Errors
/// The export is not format 10 or later, or has no skills.
pub fn generate(export: &Value) -> Result<String, String> {
    let format = export.get("format").and_then(Value::as_u64).unwrap_or(0);
    if format < MIN_FORMAT {
        return Err(format!(
            "the export is format {format}; pob-skills needs {MIN_FORMAT} or later"
        ));
    }
    let skills = export
        .get("skills")
        .and_then(Value::as_object)
        .ok_or("the export has no skills")?;
    let mut out = String::new();
    out.push_str("//! Generated by `loom-parity-cli pob-skills` from the PoB v2.67.2 data\n");
    out.push_str("//! export (`tools/oracle/data/pob_data.lua`, format 10): PoB's\n");
    out.push_str("//! hand-written skill data (`Data/Skills/*.lua`). Do not edit; see\n");
    out.push_str("//! [`super::pob_skill`]. PoB is MIT licensed.\n\n");
    out.push_str("use super::pob_skill::{PobBaseMod, PobPart, PobSkill, Value as V};\n\n");
    out.push_str("/// Every skill with hand-written data, sorted by ID.\n");
    out.push_str("pub static SKILLS: &[PobSkill] = &[\n");
    // serde_json's map is sorted (no `preserve_order`), so ids come sorted.
    let mut ids: Vec<&String> = skills.keys().collect();
    ids.sort();
    for id in ids {
        let Some(skill) = skills.get(id) else {
            continue;
        };
        let strings = |key: &str| -> Vec<String> {
            let mut v: Vec<String> = skill
                .get(key)
                .and_then(Value::as_array)
                .map(|a| {
                    a.iter()
                        .filter_map(Value::as_str)
                        .map(str::to_owned)
                        .collect()
                })
                .unwrap_or_default();
            v.sort();
            v
        };
        let flags = strings("base_flags");
        let functions = strings("functions");
        // In PoB's order: the first is the skill's default minion.
        let ordered = |key: &str| -> Vec<String> {
            skill
                .get(key)
                .and_then(Value::as_array)
                .map(|a| {
                    a.iter()
                        .filter_map(Value::as_str)
                        .map(str::to_owned)
                        .collect()
                })
                .unwrap_or_default()
        };
        let minions = ordered("minions");
        let add_minions = ordered("add_minions");
        // The stats PoB's stat map sends to the skill's minion (a
        // `MinionModifier` mod; P6-7b3a), sorted.
        let mut minion_stats: Vec<String> = skill
            .get("mods")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter(|m| {
                m.get("mods").and_then(Value::as_array).is_some_and(|mods| {
                    mods.iter()
                        .any(|x| x.get("name").and_then(Value::as_str) == Some("MinionModifier"))
                })
            })
            .filter_map(|m| m.get("stat").and_then(Value::as_str))
            .filter(|s| !s.is_empty())
            .map(str::to_owned)
            .collect();
        minion_stats.sort();
        minion_stats.dedup();
        let parts: Vec<String> = skill
            .get("parts")
            .and_then(Value::as_array)
            .map(|parts| {
                parts
                    .iter()
                    .map(|p| {
                        let mut fields: Vec<(String, String)> = p
                            .as_object()
                            .map(|o| {
                                o.iter()
                                    .filter_map(|(k, v)| lit_value(v).map(|l| (k.clone(), l)))
                                    .collect()
                            })
                            .unwrap_or_default();
                        fields.sort();
                        let values: Vec<String> = fields
                            .iter()
                            .map(|(k, l)| format!("({}, {l})", lit_str(k)))
                            .collect();
                        format!("PobPart {{ values: &[{}] }}", values.join(", "))
                    })
                    .collect()
            })
            .unwrap_or_default();
        let base_mods: Vec<String> = skill
            .get("mods")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter(|m| m.get("stat").and_then(Value::as_str) == Some(""))
            .filter_map(|m| m.get("mods").and_then(Value::as_array))
            .flatten()
            .map(|m| {
                let name = m.get("name").and_then(Value::as_str).unwrap_or("");
                let kind = m.get("type").and_then(Value::as_str).unwrap_or("");
                let fields = m.get("value_fields");
                let key = fields.and_then(|f| f.get("key")).and_then(Value::as_str);
                let value = m
                    .get("value")
                    .and_then(lit_value)
                    .or_else(|| fields.and_then(|f| f.get("value")).and_then(lit_value));
                let tagged = m
                    .get("tags")
                    .is_some_and(|t| t.as_array().is_some_and(|a| !a.is_empty()) || t.as_object().is_some_and(|o| !o.is_empty()));
                format!(
                    "PobBaseMod {{ name: {}, kind: {}, key: {}, value: {}, flags: {}, keyword_flags: {}, tagged: {tagged} }}",
                    lit_str(name),
                    lit_str(kind),
                    key.map_or_else(|| "None".to_owned(), |k| format!("Some({})", lit_str(k))),
                    value.map_or_else(|| "None".to_owned(), |v| format!("Some({v})")),
                    bits(m.get("flags")),
                    bits(m.get("keywordFlags")),
                )
            })
            .collect();
        // The stats of the skill's own `statMap` with a tagged mod acting
        // on the skill itself (tags, none `GlobalEffect`: a part, a
        // multiplier, a condition): PoB reads them under that tag, which the
        // engine's mapping does not (P6-6b review). Untagged own mods are
        // the stat's plain reading.
        // A tag that leaves the skill's own hit alone: `GlobalEffect` (a buff
        // for others), or PoB's `notMinionStat` marker (`ActorCondition` on
        // the parent, negated: not for minions; `Data.lua` 81 to 91).
        let is_global = |tag: &Value| {
            let kind = tag.get("type").and_then(Value::as_str);
            kind == Some("GlobalEffect")
                || (kind == Some("ActorCondition")
                    && tag.get("actor").and_then(Value::as_str) == Some("parent")
                    && tag.get("neg").and_then(Value::as_bool) == Some(true))
        };
        let tags_of = |m: &Value| -> Vec<Value> {
            match m.get("tags") {
                Some(Value::Array(a)) => a.clone(),
                Some(Value::Object(o)) => o.values().cloned().collect(),
                _ => Vec::new(),
            }
        };
        let mut own_stats: Vec<String> = skill
            .get("mods")
            .and_then(Value::as_array)
            .into_iter()
            .flatten()
            .filter(|m| m.get("own").and_then(Value::as_bool) == Some(true))
            .filter_map(|m| {
                let stat = m.get("stat").and_then(Value::as_str)?;
                let mods = m.get("mods").and_then(Value::as_array)?;
                let on_skill = mods.iter().any(|x| {
                    let tags = tags_of(x);
                    !tags.is_empty() && !tags.iter().any(is_global)
                });
                (!stat.is_empty() && on_skill).then(|| stat.to_owned())
            })
            .collect();
        own_stats.sort();
        if flags.is_empty()
            && parts.is_empty()
            && base_mods.is_empty()
            && functions.is_empty()
            && own_stats.is_empty()
            && minions.is_empty()
            && add_minions.is_empty()
            && minion_stats.is_empty()
        {
            continue;
        }
        let list = |v: &[String]| v.iter().map(|s| lit_str(s)).collect::<Vec<_>>().join(", ");
        let _ = writeln!(out, "    PobSkill {{");
        let _ = writeln!(out, "        id: {},", lit_str(id));
        let _ = writeln!(out, "        flags: &[{}],", list(&flags));
        let _ = writeln!(out, "        parts: &[{}],", parts.join(", "));
        let _ = writeln!(out, "        base_mods: &[{}],", base_mods.join(", "));
        let _ = writeln!(out, "        functions: &[{}],", list(&functions));
        let _ = writeln!(out, "        own_stats: &[{}],", list(&own_stats));
        let _ = writeln!(out, "        minions: &[{}],", list(&minions));
        let _ = writeln!(out, "        add_minions: &[{}],", list(&add_minions));
        let _ = writeln!(out, "        minion_stats: &[{}],", list(&minion_stats));
        let _ = writeln!(out, "    }},");
    }
    out.push_str("];\n");
    Ok(out)
}

/// The Rust source of the minion table (module docs), sorted by name.
///
/// # Errors
/// The export is not format 13 or later, or an entry is malformed.
pub fn generate_minions(export: &Value) -> Result<String, String> {
    let format = export.get("format").and_then(Value::as_u64).unwrap_or(0);
    if format < MINION_FORMAT {
        return Err(format!(
            "the export is format {format}; pob-minions needs {MINION_FORMAT} or later"
        ));
    }
    let templates = export
        .get("minion_templates")
        .and_then(Value::as_object)
        .ok_or("the export has no minion_templates")?;
    let mut out = String::new();
    out.push_str("//! Generated by `loom-parity-cli pob-minions` from the PoB v2.67.2 data\n");
    out.push_str("//! export (`tools/oracle/data/pob_data.lua`, format 13): what PoB's\n");
    out.push_str("//! minion templates (`Export/Minions/*.txt`) add to each game variety.\n");
    out.push_str("//! Do not edit; see [`super::pob_minion`]. PoB is MIT licensed.\n\n");
    out.push_str("use super::pob_minion::{PobMinion, PobMinionMod, Template};\n\n");
    out.push_str("/// Every minion PoB's templates emit, sorted by PoB's name.\n");
    out.push_str("pub static MINIONS: &[PobMinion] = &[\n");
    // Sorted by name here, whatever order the JSON map keeps.
    let mut names: Vec<(&String, &Value)> = templates.iter().collect();
    names.sort_by(|a, b| a.0.cmp(b.0));
    for (name, t) in names {
        let text = |key: &str| t.get(key).and_then(Value::as_str);
        let file = match text("file") {
            Some("Minions") => "Template::Minions",
            Some("Spectres") => "Template::Spectres",
            other => return Err(format!("{name}: template file {other:?}")),
        };
        let line = t
            .get("line")
            .and_then(Value::as_u64)
            .ok_or_else(|| format!("{name}: no line"))?;
        let variety = text("variety").ok_or_else(|| format!("{name}: no variety"))?;
        let opt = |key: &str| {
            text(key).map_or_else(|| "None".to_owned(), |s| format!("Some({})", lit_str(s)))
        };
        let items = |key: &str| -> Vec<&Value> {
            t.get(key)
                .and_then(Value::as_array)
                .map(|a| a.iter().collect())
                .unwrap_or_default()
        };
        let skills: Vec<String> = items("skills")
            .into_iter()
            .filter_map(Value::as_str)
            .map(lit_str)
            .collect();
        let mods = items("mods")
            .into_iter()
            .map(|m| {
                let line = m
                    .get("line")
                    .and_then(Value::as_u64)
                    .ok_or_else(|| format!("{name}: a mod without a line"))?;
                let text = m
                    .get("text")
                    .and_then(Value::as_str)
                    .ok_or_else(|| format!("{name}: a mod without text"))?;
                Ok(format!(
                    "PobMinionMod {{ line: {line}, text: {} }}",
                    lit_str(text)
                ))
            })
            .collect::<Result<Vec<String>, String>>()?;
        let _ = writeln!(out, "    PobMinion {{");
        let _ = writeln!(out, "        name: {},", lit_str(name));
        let _ = writeln!(out, "        template: {file},");
        let _ = writeln!(out, "        line: {line},");
        let _ = writeln!(out, "        variety: {},", lit_str(variety));
        let _ = writeln!(out, "        limit: {},", opt("limit"));
        let _ = writeln!(out, "        hostile: {},", opt("hostile"));
        let _ = writeln!(out, "        skills: &[{}],", skills.join(", "));
        let _ = writeln!(out, "        mods: &[{}],", mods.join(", "));
        let _ = writeln!(out, "    }},");
    }
    out.push_str("];\n");
    Ok(out)
}

/// Reads the export and writes the skill table ([`generate`]).
///
/// # Errors
/// I/O, JSON, or [`generate`]'s.
pub fn run_skills(export: &Path, out: &Path) -> Result<bool, String> {
    write_table(export, out, generate)
}

/// Reads the export and writes the minion table ([`generate_minions`]).
///
/// # Errors
/// I/O, JSON, or [`generate_minions`]'s.
pub fn run_minions(export: &Path, out: &Path) -> Result<bool, String> {
    write_table(export, out, generate_minions)
}

fn write_table(
    export: &Path,
    out: &Path,
    generator: fn(&Value) -> Result<String, String>,
) -> Result<bool, String> {
    let text = std::fs::read_to_string(export).map_err(|e| format!("{}: {e}", export.display()))?;
    let json: Value =
        serde_json::from_str(&text).map_err(|e| format!("{}: {e}", export.display()))?;
    let source = generator(&json)?;
    std::fs::write(out, source).map_err(|e| format!("{}: {e}", out.display()))?;
    Ok(true)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn generate_should_write_sorted_skills_with_their_data() {
        let export = serde_json::json!({
            "format": 10,
            "skills": {
                "B": {"base_flags": ["spell", "area"], "parts": [], "functions": [], "mods": [
                    {"stat": "", "mods": [{"name": "SkillData", "type": "LIST", "flags": 0, "keywordFlags": 0, "tags": {}, "value_fields": {"key": "dotIsArea", "value": true}}]}
                ]},
                "A": {"base_flags": [], "parts": [{"name": "Hit", "area": false}], "functions": ["preDamageFunc"], "mods": []},
                "C": {"base_flags": [], "parts": [], "functions": [], "mods": []}
            }
        });
        let src = generate(&export).expect("generates");
        let a = src.find("id: \"A\"").expect("A");
        let b = src.find("id: \"B\"").expect("B");
        assert!(a < b);
        assert!(!src.contains("id: \"C\""));
        assert!(src.contains("flags: &[\"area\", \"spell\"]"));
        assert!(src.contains("(\"area\", V::Bool(false)), (\"name\", V::Str(\"Hit\"))"));
        assert!(src.contains("key: Some(\"dotIsArea\"), value: Some(V::Bool(true))"));
        assert!(generate(&serde_json::json!({"format": 9, "skills": {}})).is_err());
        assert_eq!(lit_num(2.0), "2.0");
        assert_eq!(lit_num(0.057300001382828), "0.057300001382828");
    }

    /// Skills' minion lists keep PoB's order (the first is the default), and
    /// the minion table is sorted by name with each directive.
    #[test]
    fn generate_should_write_minion_lists_and_the_minion_table() {
        let export = serde_json::json!({
            "format": 13,
            "skills": {
                "Raise": {"base_flags": [], "parts": [], "functions": [], "mods": [],
                    "minions": ["Zed", "Abe"], "add_minions": {}}
            },
            "minion_templates": {
                "Zed": {"file": "Minions", "line": 4, "variety": "Metadata/Monsters/Z",
                    "limit": "ActiveZLimit", "skills": ["Extra"],
                    "mods": [{"line": 6, "text": "mod(\"Life\", \"MORE\", 10)"}]},
                "Abe": {"file": "Spectres", "line": 9, "variety": "Metadata/Monsters/A",
                    "hostile": "true", "skills": {}, "mods": {}}
            }
        });
        let src = generate(&export).expect("generates");
        assert!(src.contains("minions: &[\"Zed\", \"Abe\"],"), "{src}");
        let table = generate_minions(&export).expect("generates");
        let (abe, zed) = (
            table.find("\"Abe\"").expect("Abe"),
            table.find("\"Zed\"").expect("Zed"),
        );
        assert!(abe < zed);
        assert!(table.contains("template: Template::Spectres,"));
        assert!(table.contains("hostile: Some(\"true\"),"));
        assert!(table.contains("limit: Some(\"ActiveZLimit\"),"));
        assert!(table.contains("skills: &[\"Extra\"],"));
        assert!(
            table.contains(
                "PobMinionMod { line: 6, text: \"mod(\\\"Life\\\", \\\"MORE\\\", 10)\" }"
            ),
            "{table}"
        );
        assert!(generate_minions(&serde_json::json!({"format": 12})).is_err());
    }
}
