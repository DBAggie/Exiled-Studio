//! Supports an item grants its socketed gems (P6-11r): "Socketed Gems are
//! Supported by Level # <Support>" and its kin.
//!
//! What PoB v2.67.2 does:
//! - `Modules/ModParser.lua` 3371 and 3372 read the line ("socketed [%a+]*
//!   ?gems a?r?e? ?supported by level (%d+) (.+)", and the "spells" form)
//!   with `extraSupport` (2071 to 2104): the name is looked up as a granted
//!   effect (`gemIdLookup`), then the gem named "<name> Support" gives its
//!   granted effect, and its secondary one when that is a support, each an
//!   `ExtraSupport` LIST modifier `{ skillId, level }` tagged `SocketedIn`
//!   with the item's slot. A secondary effect that is not a support is an
//!   `ExtraSkill` instead;
//! - `Modules/CalcSetup.lua` 1525 to 1555 adds each `ExtraSupport` of the
//!   group's slot to the group's support list before the group's own
//!   supports, at the line's level and quality 0, unless the group is an
//!   item's (`group.source`); no gem level modifier changes it. The group's
//!   supports then join by `addBestSupport` (338 to 367): one with the same
//!   granted effect as a support already there replaces it only with a
//!   higher level, or the same level and a higher quality;
//! - `calcLib.canGrantedEffectSupportActiveSkill` (`CalcTools.lua` 94) keeps
//!   an item's support from an active skill an item grants.
//!
//! **The engine.** [`ROWS`] is PoB's parse of each stat's English line
//! (the stat at 10; rows whose level is in the text carry it), generated
//! from the bundle by a local script and checked by a maintainer-run test
//! against the bundle's texts and gems. A row's stat on an item in an
//! equipment slot maps to [`super::Poe1Quantity::ItemSupport`] for that
//! slot ([`super::gem_levels::InSlot`]); [`super::gem_levels::GemLevels`]
//! keeps them in order, and [`super::skill`] adds them to the groups in the
//! slot. Left unmapped, reasons: the lines PoB does not parse, the ones
//! that also grant a skill (`ExtraSkill`), and the ones naming a slot.
//!
//! The support's gem index is past the group's gems (a support from an
//! item has no gem); its stats' source is that index. PoB's
//! `plusVersionOf` (an awakened support replacing its plain one) is not in
//! the bundle: not modelled.

